export const MESSAGES: Record<AppLanguage, Readonly<Record<MessageKey, string>>> = {
  en: englishMessages,
  'es-MX': spanishMessages,
};

export const MAIN_NAV_ITEMS = [
  { id: 'apps', route: '/(main)', labelKey: 'nav.apps', icon: 'grid-outline' },
  { id: 'saved', route: '/(main)/saved', labelKey: 'nav.saved', icon: 'star-outline' },
  { id: 'settings', route: '/(main)/settings', labelKey: 'nav.settings', icon: 'settings-outline' },
] as const satisfies readonly {
  id: 'apps' | 'saved' | 'settings';
  route: '/(main)' | '/(main)/saved' | '/(main)/settings';
  labelKey: MessageKey;
  icon: string;
}[];

export function translateMessage(language: AppLanguage, key: MessageKey): string {
  return MESSAGES[language]?.[key] ?? MESSAGES.en[key];
}

export function resolveMainNavigationSelection(pathname: string): 'apps' | 'saved' | 'settings' {
  if (pathname.includes('/saved')) return 'saved';
  if (pathname.includes('/settings')) return 'settings';
  return 'apps';
}
